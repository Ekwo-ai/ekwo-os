#!/usr/bin/env node
/**
 * Builds `src/codelists.ts` from the code tables LHDNM publishes with the
 * MyInvois SDK, and the ISO 3166-1 table of the United Nations Statistics
 * Division.
 *
 * A code list is not something to type. LHDNM publishes every table of the
 * SDK as a JSON file beside its page — the e-invoice types, the tax types,
 * the classification codes, the MSIC codes, the states, the countries, the
 * currencies, the units, the payment modes — and those files are kept,
 * unmodified, under `test/codelist/`. This script reads them and writes what
 * it finds, in the order it finds it.
 *
 * One table is not LHDNM's. The books hold a country as its two-letter ISO
 * 3166-1 code; MyInvois wants the three-letter one. The pairs are read from
 * the M49 table of the UN Statistics Division (`test/codelist/m49-iso-alpha.csv`,
 * extracted as its README says), and only a pair whose three-letter code is
 * in LHDNM's list is kept: a code LHDNM does not accept is not one to write.
 *
 *   node scripts/build-codelists.mjs           rewrite src/codelists.ts
 *   node scripts/build-codelists.mjs --check   fail if it is not up to date
 *
 * To move to a new release of the SDK: replace the files under
 * `test/codelist/`, run this, run the tests.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'test', 'codelist');
const TARGET = join(ROOT, 'src', 'codelists.ts');

const read = (file) => JSON.parse(readFileSync(join(SOURCE, file), 'utf8'));

/** Code and label, for the short tables a message quotes. */
const TABLES = [
  { name: 'EINVOICE_TYPES', file: 'EInvoiceTypes.json', label: 'Description', what: 'e-Invoice types (`cbc:InvoiceTypeCode`)', page: 'codes/e-invoice-types' },
  { name: 'TAX_TYPES', file: 'TaxTypes.json', label: 'Description', what: 'Tax types (`cac:TaxCategory/cbc:ID`)', page: 'codes/tax-types' },
  { name: 'CLASSIFICATION_CODES', file: 'ClassificationCodes.json', label: 'Description', what: 'Classification codes (`cbc:ItemClassificationCode[@listID="CLASS"]`)', page: 'codes/classification-codes' },
  { name: 'STATE_CODES', file: 'StateCodes.json', label: 'State', what: 'State codes (`cbc:CountrySubentityCode`)', page: 'codes/state-codes' },
  { name: 'PAYMENT_MODES', file: 'PaymentMethods.json', label: 'Payment Method', what: 'Payment modes (`cbc:PaymentMeansCode`)', page: 'codes/payment-methods' },
];

/** Codes only, for the long tables that are checked and never quoted. */
const SETS = [
  { name: 'COUNTRY_CODES', file: 'CountryCodes.json', what: 'Country codes, ISO 3166-1 alpha-3 (`cac:Country/cbc:IdentificationCode`)', page: 'codes/countries' },
  { name: 'CURRENCY_CODES', file: 'CurrencyCodes.json', what: 'Currency codes, ISO 4217 (`cbc:DocumentCurrencyCode`)', page: 'codes/currencies' },
  { name: 'UNIT_CODES', file: 'UnitTypes.json', what: 'Unit types, UN/ECE Recommendation 20 (`cbc:InvoicedQuantity/@unitCode`)', page: 'codes/unit-types' },
  { name: 'MSIC_CODES', file: 'MSICSubCategoryCodes.json', what: 'MSIC codes (`cbc:IndustryClassificationCode`)', page: 'codes/msic-codes' },
];

const quote = (text) => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** A long list of codes, as one string cut in lines of a readable width. */
function wrapped(codes) {
  const lines = [];
  let line = '';
  for (const code of codes) {
    if (line !== '' && line.length + code.length + 1 > 96) {
      lines.push(line);
      line = '';
    }
    line += line === '' ? code : ` ${code}`;
  }
  if (line !== '') lines.push(line);
  return lines.map((each, index) => `  '${each}${index < lines.length - 1 ? " ' +" : "'"}`).join('\n');
}

export function build() {
  const out = [
    '/**',
    ' * GENERATED by `scripts/build-codelists.mjs` — do not edit.',
    ' *',
    ' * Read from the JSON files LHDNM publishes with the MyInvois SDK,',
    ' * <https://sdk.myinvois.hasil.gov.my/codes/>, kept under `test/codelist/`.',
    ' * `test/codelists.test.ts` compares every list here with those files.',
    ' */',
    '',
    "const list = (codes: string): ReadonlySet<string> => new Set(codes.split(' '));",
    '',
  ];

  for (const table of TABLES) {
    const rows = read(table.file);
    out.push(`/** ${table.what}: ${rows.length} codes. From \`${table.file}\`, <https://sdk.myinvois.hasil.gov.my/${table.page}/>. */`);
    out.push(`export const ${table.name}: Readonly<Record<string, string>> = {`);
    for (const row of rows) out.push(`  ${quote(row.Code)}: ${quote(String(row[table.label]).trim())},`);
    out.push('};', '');
  }

  const sets = {};
  for (const set of SETS) {
    const codes = read(set.file).map((row) => String(row.Code).trim());
    sets[set.name] = new Set(codes);
    out.push(`/** ${set.what}: ${codes.length} codes. From \`${set.file}\`, <https://sdk.myinvois.hasil.gov.my/${set.page}/>. */`);
    out.push(`export const ${set.name}: ReadonlySet<string> = list(`);
    out.push(wrapped(codes));
    out.push(');', '');
  }

  const pairs = readFileSync(join(SOURCE, 'm49-iso-alpha.csv'), 'utf8')
    .trim()
    .split('\n')
    .slice(1)
    .map((line) => line.split(',').slice(0, 2))
    .filter(([, alpha3]) => sets.COUNTRY_CODES.has(alpha3));
  out.push(
    `/**`,
    ` * ISO 3166-1 alpha-2 to alpha-3: ${pairs.length} pairs. From the M49 table of the UN Statistics`,
    ` * Division (\`m49-iso-alpha.csv\`), <https://unstats.un.org/unsd/methodology/m49/overview/>,`,
    ` * kept where the alpha-3 code is in COUNTRY_CODES.`,
    ` */`,
    `export const ALPHA3: Readonly<Record<string, string>> = {`,
  );
  for (const [alpha2, alpha3] of pairs) out.push(`  ${alpha2}: '${alpha3}',`);
  out.push('};', '');
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = build();
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== text) {
      console.error('src/codelists.ts is not what the files under test/codelist/ say: run `npm run codelists`.');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, text);
  }
}
