#!/usr/bin/env node
/**
 * Builds `src/codelists.ts` from the Schematron the rules of EN 16931 are
 * published as.
 *
 * A code list is not something to type. The list of units of UN/ECE
 * Recommendation 20 has over two thousand entries and the list of electronic
 * address schemes gains one every few months; a copy made by hand is wrong the
 * day it is made and nobody can tell where. So the lists are read out of the
 * `BR-CL-*` assertions of `test/codelist/CEN-EN16931-UBL.sch` — the file a
 * Peppol access point validates with — and written as they are found.
 *
 *   node scripts/build-codelists.mjs           rewrite src/codelists.ts
 *   node scripts/build-codelists.mjs --check   fail if it is not up to date
 *
 * To move to a new release: replace the file under `test/codelist/`, run this,
 * run the tests. `test/codelist/README.md` says where the file comes from.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'test', 'codelist', 'CEN-EN16931-UBL.sch');
const TARGET = join(ROOT, 'src', 'codelists.ts');

/**
 * What is read, and under which name it is exported. `index` is which of the
 * quoted lists of the assertion is meant, for the one rule that has two.
 */
const LISTS = [
  { name: 'CURRENCY_CODES', rule: 'BR-CL-04', index: 0, what: 'ISO 4217 currency codes (BT-5)' },
  { name: 'COUNTRY_CODES', rule: 'BR-CL-14', index: 0, what: 'ISO 3166-1 country codes (BT-40, BT-55, BT-80)' },
  { name: 'VAT_IDENTIFIER_PREFIXES', rule: 'BR-CO-09', index: 0, what: 'Prefixes a VAT identifier may start with (BT-31, BT-48): ISO 3166-1, and EL, which is what a Greek number starts with' },
  { name: 'PAYMENT_MEANS_CODES', rule: 'BR-CL-16', index: 0, what: 'UNTDID 4461 payment means codes (BT-81)' },
  { name: 'VAT_CATEGORY_CODES', rule: 'BR-CL-18', index: 0, what: 'UNTDID 5305 duty or tax category codes, the subset of EN 16931 (BT-118, BT-151)' },
  { name: 'EXEMPTION_REASON_CODES', rule: 'BR-CL-22', index: 0, what: 'VATEX exemption reason codes (BT-121)' },
  { name: 'UNIT_CODES', rule: 'BR-CL-23', index: 0, what: 'UN/ECE Recommendation 20 and 21 unit codes (BT-130)' },
  { name: 'ELECTRONIC_ADDRESS_SCHEMES', rule: 'BR-CL-25', index: 0, what: 'Electronic address schemes, EAS (BT-34-1, BT-49-1)' },
  { name: 'IDENTIFIER_SCHEMES', rule: 'BR-CL-11', index: 0, what: 'ISO 6523 ICD identifier schemes (BT-30-1, BT-47-1)' },
];

/** The quoted, space-separated lists inside the `test` of one assertion. */
export function listsOf(schematron, rule) {
  const assertion = new RegExp(`<assert\\b[^>]*\\bid="${rule}"[^>]*>`).exec(schematron);
  if (!assertion) throw new Error(`${rule}: no such assertion in the Schematron`);
  const test = /\btest="([^"]*)"/.exec(assertion[0]);
  if (!test) throw new Error(`${rule}: the assertion has no test`);
  return [...test[1].matchAll(/contains\(\s*'([^']*)'/g)].map((match) =>
    match[1].split(/\s+/).filter((code) => code !== ''),
  );
}

function build() {
  const schematron = readFileSync(SOURCE, 'utf8');
  const version = /Schematron version ([0-9.]+)/.exec(schematron)?.[1] ?? 'unknown';
  const parts = [
    '/**',
    ' * GENERATED by `scripts/build-codelists.mjs` — do not edit.',
    ' *',
    ` * Read from the \`BR-CL-*\` assertions of the EN 16931 Schematron for UBL, version ${version},`,
    ' * as Peppol BIS Billing 3.0 ships it. `test/codelists.test.ts` compares every',
    ' * list here with that file, code for code.',
    ' */',
    '',
    "const list = (codes: string): ReadonlySet<string> => new Set(codes.split(' '));",
    '',
  ];
  for (const { name, rule, index, what } of LISTS) {
    const codes = listsOf(schematron, rule)[index];
    if (!codes || codes.length === 0) throw new Error(`${rule}: no list found`);
    parts.push(`/** ${what}. From ${rule}: ${codes.length} codes. */`);
    parts.push(`export const ${name}: ReadonlySet<string> = list(`);
    // Lines of about a hundred characters: a diff of a new release then shows
    // the codes that moved and not one line of ten thousand characters.
    const lines = [];
    let line = '';
    for (const code of codes) {
      if (line !== '' && line.length + code.length + 1 > 96) {
        lines.push(line);
        line = '';
      }
      line = line === '' ? code : `${line} ${code}`;
    }
    lines.push(line);
    parts.push(lines.map((text, i) => `  '${i < lines.length - 1 ? `${text} ` : text}'${i < lines.length - 1 ? ' +' : ','}`).join('\n'));
    parts.push(');', '');
  }
  return `${parts.join('\n').trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = build();
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== output) {
      console.error('src/codelists.ts is not what the Schematron says. Run scripts/build-codelists.mjs.');
      process.exit(1);
    }
    console.log('src/codelists.ts is up to date.');
  } else {
    writeFileSync(TARGET, output);
    console.log(`Wrote ${TARGET}`);
  }
}
